"""Regenerate the host reference for the BIOS bank extension backend."""
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory(prefix="banked-transfer-") as directory:
    binary = Path(directory) / "transfer.bin"
    subprocess.run(["z80asm", "-o", str(binary),
                    str(root / "src/common/banked_transfer.asm")], check=True)
    code = binary.read_bytes()
assert len(code) <= 0xF0, "transfer code overlaps its FFF0h parameter block"
lines = ["/* Generated by scripts/build-banked-transfer.py; do not edit. */",
         "#ifndef Z80SBC_BANKED_TRANSFER_H", "#define Z80SBC_BANKED_TRANSFER_H",
         "#define BANKED_BURST_BYTES 16", "#define BANKED_CODE_ADDRESS 0xFF00",
         "#define BANKED_PARAMETERS 0xFFF0", "#define BANKED_ABI_STATUS 0xB4",
         "#define BANKED_HEAP_END 0xDE00", "#define BANKED_HEAP_BYTES 5632U",
         "#ifdef BANKED_INCLUDE_CODE",
         "static const unsigned char banked_transfer_code[] = {"]
for offset in range(0, len(code), 12):
    lines.append("  " + ", ".join("0x%02X" % byte for byte in code[offset:offset+12]) + ",")
lines += ["};", "#endif", "#endif", ""]
for target in ("src/common/include/z80sbc/banked_transfer.h",):
    (root / target).write_text("\n".join(lines))

# The bank-1 extent allocator occupies the former CCP slot.
with tempfile.TemporaryDirectory(prefix="banked-allocator-") as directory:
    binary = Path(directory) / "allocator.bin"
    subprocess.run(["z80asm", "-o", str(binary),
                    str(root / "src/common/banked_allocator.asm")], check=True)
    allocator = binary.read_bytes()
assert len(allocator) <= 0x400, "allocator exceeds E800h..EBFFh"
lines = ["/* Generated by scripts/build-banked-transfer.py; do not edit. */",
         "#ifndef Z80SBC_BANKED_ALLOCATOR_H", "#define Z80SBC_BANKED_ALLOCATOR_H",
         "#define BANKED_ALLOCATOR_ADDRESS 0xE800",
         "#define BANKED_ALLOCATOR_CALL_REVISION 1",
         "static const unsigned char banked_allocator_code[] = {"]
for offset in range(0, len(allocator), 12):
    lines.append("  " + ", ".join("0x%02X" % byte for byte in allocator[offset:offset+12]) + ",")
lines += ["};", "#endif", ""]
(root / "src/common/include/z80sbc/banked_allocator.h").write_text("\n".join(lines))


def assemble(source: str) -> bytes:
    with tempfile.TemporaryDirectory(prefix="bank1-system-") as directory:
        binary = Path(directory) / "out.bin"
        subprocess.run(["z80asm", "-o", str(binary), str(root / source)], check=True)
        return binary.read_bytes()


def emit_array(output: list[str], name: str, data: bytes) -> None:
    output.append(f"static const unsigned char {name}[] = {{")
    for offset in range(0, len(data), 12):
        output.append("  " + ", ".join("0x%02X" % value for value in data[offset:offset + 12]) + ",")
    output.append("};")


service = bytearray(0x800)
for address, source in ((0xDE00, "src/common/bank1_bdos_proxy.asm"),
                        (0xE000, "src/common/bank1_library_loader.asm"),
                        (0xE360, "src/common/banked_capabilities.asm"),
                        (0xE390, "src/common/banked_descriptor.asm")):
    binary = assemble(source)
    if address == 0xE000:
        assert len(binary) <= 0x300, "library loader overlaps E300h export buffer"
    elif address == 0xDE00:
        assert len(binary) <= 0x8E, "BDOS proxy overlaps loader metadata"
    elif address == 0xE360:
        assert len(binary) == 48, "capability record must contain 24 words"
    elif address == 0xE390:
        assert len(binary) <= 0x70, "descriptor helpers overlap the BDOS DMA buffer"
    offset = address - 0xDE00
    assert offset + len(binary) <= len(service)
    service[offset:offset + len(binary)] = binary
service[0x180] = 0x80  # Initial library DMA is page-zero's default buffer.
service[0x1A6] = 1     # Nonzero pool epoch; RESET must never wrap it.

resident = bytearray(0x800)
resident[:9] = b"BKM1BEX1\x01"
resident[0x10] = 8
resident[0x14:0x16] = b"\x00\x16"
resident[0x101] = 0xBF
resident[0x102] = 8
resident[0x108] = 22
resident[0x122] = 1
resident[0x128] = 2
resident[0x141] = resident[0x142] = 0xFF
entry = assemble("src/common/banked_service_entry.asm")
assert len(entry) <= 0x64
resident[0x40:0x40 + len(entry)] = entry
context = assemble("src/common/banked_context.asm")
assert len(context) <= 0x80
resident[0x180:0x180 + len(context)] = context
resident[0x200:0x200 + len(allocator)] = allocator
extensions = assemble("src/common/banked_extensions.asm")
assert len(extensions) <= 0x200
resident[0x600:0x600 + len(extensions)] = extensions

system = assemble("src/cpm/cpm64_z80.asm")
assert len(system) == 0x1600
bdos = system[0x800:0x1540]
output = ["/* Generated by scripts/build-banked-transfer.py; do not edit. */",
          "#ifndef Z80SBC_BANK1_SYSTEM_H", "#define Z80SBC_BANK1_SYSTEM_H"]
emit_array(output, "bank1_service_code", service)
emit_array(output, "bank1_resident_code", resident)
emit_array(output, "bank1_bdos_code", bdos)
output += ["#endif", ""]
(root / "src/common/include/z80sbc/bank1_system.h").write_text("\n".join(output))
